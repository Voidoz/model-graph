"""Markdown + JSON training report."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from modelgraph.util import utc_now


def write_training_report(report: dict[str, Any], path: str | Path) -> Path:
    destination = Path(path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    document = dict(report)
    document["created_at"] = utc_now()
    destination.write_text(render_markdown(document), encoding="utf-8")
    json_path = destination.with_suffix(".json")
    json_path.write_text(
        json.dumps(document, indent=2, sort_keys=True, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    return destination


def render_markdown(report: dict[str, Any]) -> str:
    lines: list[str] = []
    artifact = report.get("artifact", {})
    dataset = report.get("dataset", {})
    summary = dataset.get("summary", {})
    metrics = report.get("metrics", {})
    trained = metrics.get("trained", {})
    rules = metrics.get("rules", {})
    incumbent = metrics.get("incumbent", {})
    lines.append("# Router training report")
    lines.append("")
    lines.append(
        "This report is generated by `mg train router`. It is a routing-only evaluation on "
        "exported data; it does not by itself establish an end-to-end quality win."
    )
    lines.append("")
    lines.append("## Reproduction")
    lines.append("")
    lines.append(f"- command: `{report.get('command') or 'mg train router --config <config>'}`")
    lines.append(f"- seed: `{report.get('seed')}`")
    lines.append(f"- artifact: `{artifact.get('path')}` (`{artifact.get('sha256')}`)")
    lines.append(f"- artifact schema: `{artifact.get('schema')} v{artifact.get('version')}`")
    lines.append(f"- created_at: `{report.get('created_at')}`")
    config = report.get("config", {})
    lines.append(f"- config hash: `{config.get('config_hash', '<embedded>')}`")
    lines.append("")
    lines.append("## Dataset")
    lines.append("")
    dataset_info = summary.get("dataset", {})
    lines.append(f"- id/version: `{dataset_info.get('id')}` / `{dataset_info.get('version')}`")
    lines.append(f"- manifest hash: `{dataset_info.get('hash')}`")
    lines.append(f"- frozen test: `{dataset_info.get('frozen_test')}`")
    lines.append(f"- examples: `{summary.get('examples')}`")
    lines.append(f"- excluded: `{summary.get('excluded')}`")
    lines.append("")
    lines.append("| split | examples | groups | ambiguous |")
    lines.append("| --- | ---: | ---: | ---: |")
    counts = summary.get("counts", {})
    groups = summary.get("groups", {})
    ambiguity = summary.get("ambiguity", {})
    for split in ("train", "validation", "test"):
        lines.append(
            f"| {split} | {counts.get(split, 0)} | {groups.get(split, 0)} | "
            f"{ambiguity.get(split, 0)} |"
        )
    lines.append("")
    lines.append("### Class balance")
    lines.append("")
    classes = sorted(
        {name for values in summary.get("class_balance", {}).values() for name in values}
    )
    lines.append("| split | " + " | ".join(classes) + " |")
    lines.append("| --- | " + " | ".join("---:" for _ in classes) + " |")
    for split in ("train", "validation", "test"):
        values = summary.get("class_balance", {}).get(split, {})
        lines.append(
            f"| {split} | " + " | ".join(str(values.get(name, 0)) for name in classes) + " |"
        )
    lines.append("")
    lines.append("## Calibration")
    lines.append("")
    calibration = report.get("calibration", {})
    lines.append(f"- method: `{calibration.get('method')}`")
    lines.append(f"- fit split: `{calibration.get('fit_split')}` (test is never used to fit)")
    lines.append(f"- fit count: `{calibration.get('fit_count')}`")
    lines.append(f"- temperature: `{_number(calibration.get('temperature'))}`")
    reliability = report.get("reliability", {})
    for split in ("validation", "test"):
        entry = reliability.get(split, {})
        before = entry.get("before", {})
        after = entry.get("after", {})
        lines.append(
            f"- {split} ECE: before `{_number(before.get('ece'))}`, after "
            f"`{_number(after.get('ece'))}` (n={after.get('n')})"
        )
    lines.append("")
    lines.append(
        "Reliability is computed on routed, non-ambiguous predictions accepted at the "
        "abstain threshold; the before/after rows use the same cases."
    )
    lines.append("")
    lines.append("### Reliability table (test, after calibration)")
    lines.append("")
    lines.append("| bin | n | mean confidence | accuracy | gap |")
    lines.append("| --- | ---: | ---: | ---: | ---: |")
    for entry in reliability.get("test", {}).get("after", {}).get("bins", []):
        lines.append(
            f"| {entry['lower']:.2f}–{entry['upper']:.2f} | {entry['count']} | "
            f"{_number(entry['confidence'])} | {_number(entry['accuracy'])} | "
            f"{_number(entry['gap'])} |"
        )
    lines.append("")
    lines.append("## Abstention")
    lines.append("")
    abstain = report.get("abstain", {})
    lines.append(f"- threshold: `{_number(abstain.get('threshold'))}`")
    lines.append("- selected on: `validation` (cost matrix below; test is reported once)")
    lines.append("")
    lines.append("| outcome | cost |")
    lines.append("| --- | ---: |")
    for name, value in sorted((abstain.get("cost_matrix") or {}).items()):
        lines.append(f"| {name} | {_number(value)} |")
    lines.append("")
    lines.append("## Routing metrics")
    lines.append("")
    lines.append(
        "| model | split | oracle agreement | coverage | abstain rate | abstain P | "
        "abstain R | ECE | cost/case |"
    )
    lines.append("| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |")
    for model_name, values in (
        ("trained", trained),
        ("rules", rules),
        ("incumbent", incumbent),
    ):
        for split in ("validation", "test"):
            entry = values.get(split, {})
            lines.append(
                f"| {model_name} | {split} | {_rate(entry.get('oracle_agreement'))} | "
                f"{_rate(entry.get('coverage'))} | {_rate(entry.get('abstain_rate'))} | "
                f"{_rate(entry.get('abstain_precision'))} | "
                f"{_rate(entry.get('abstain_recall'))} | {_rate(entry.get('ece'))} | "
                f"{_number(entry.get('expected_cost_per_case'))} |"
            )
    lines.append("")
    lines.append("### Confusion (test, trained)")
    lines.append("")
    confusion = trained.get("test", {}).get("confusion", {})
    lines.append(_confusion_table(confusion))
    lines.append("")
    lines.append("## Recommendation")
    lines.append("")
    recommendation = report.get("recommendation", {})
    lines.append(f"- promote: `{recommendation.get('promote')}`")
    lines.append(f"- reason: {recommendation.get('reason')}")
    lines.append(
        f"- trained test oracle agreement: "
        f"`{_rate(recommendation.get('trained_test_oracle_agreement'))}`"
    )
    lines.append(
        f"- best comparator test oracle agreement: "
        f"`{_rate(recommendation.get('best_comparator_test_oracle_agreement'))}`"
    )
    lines.append(
        f"- trained test cost/case: `{_number(recommendation.get('trained_test_cost_per_case'))}`"
    )
    lines.append(
        f"- best comparator test cost/case: "
        f"`{_number(recommendation.get('best_comparator_test_cost_per_case'))}`"
    )
    lines.append("")
    lines.append("## Limitations")
    lines.append("")
    for limitation in report.get("limitations", []):
        lines.append(f"- {limitation}")
    lines.append("")
    return "\n".join(lines)


def _confusion_table(confusion: dict[str, dict[str, int]]) -> str:
    if not confusion:
        return "_No confusion data._"
    chosen = sorted({name for row in confusion.values() for name in row})
    lines = ["| oracle \\ chosen | " + " | ".join(chosen) + " |"]
    lines.append("| --- | " + " | ".join("---:" for _ in chosen) + " |")
    for oracle in sorted(confusion):
        values = confusion[oracle]
        lines.append(
            f"| {oracle} | " + " | ".join(str(values.get(name, 0)) for name in chosen) + " |"
        )
    return "\n".join(lines)


def _number(value: Any) -> str:
    if isinstance(value, (int, float)):
        return f"{float(value):.3f}"
    return "n/a"


def _rate(value: Any) -> str:
    if isinstance(value, (int, float)):
        return f"{float(value):.3f}"
    return "n/a"
